#!/usr/bin/env python3
"""Generate the nao sidecar's secrets into the git-ignored ``data/`` directory (Task 3N).

Guarantees required by the brief:

* every secret comes from the :mod:`secrets` CSPRNG (never ``random``, never a literal);
* **nothing is written** unless the target paths are already git-ignored (verified first with
  ``git check-ignore``, so a mis-configured ``.gitignore`` can never leak a secret into git);
* secret *values* are never printed — only the file paths and a count;
* the root ``.env`` is never read or modified beyond reading an existing value to avoid churn;
* re-running is safe: an existing ``data/nao-secrets.env`` is left untouched (no rotation, no
  reset of the persisted credential store).

Outputs (both git-ignored, both written mode 0600):

* ``data/nao-secrets.env``  — ``BETTER_AUTH_SECRET``, ``COPILOT_MCP_SECRET``,
  ``COPILOT_MCP_DISCOVERY_TOKEN``, the reserved-``.invalid`` service ``NAO_SERVICE_EMAIL`` and
  its ``NAO_SERVICE_PASSWORD``, plus the non-secret ``NAO_APP_USER_ID`` the account maps to.
* ``data/nao-credentials.json`` — the running ``app_user_id -> nao account`` mapping store. It is
  *created empty* here and populated by ``bootstrap/nao-bootstrap.ts`` (which is the only place a
  password is ever materialised, and it never prints it).
"""
from __future__ import annotations

import argparse
import secrets
import subprocess
import sys
import uuid
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
DATA_DIR = REPO_ROOT / "data"
SECRETS_ENV = DATA_DIR / "nao-secrets.env"
CREDENTIALS = DATA_DIR / "nao-credentials.json"

# Each target must be git-ignored *before* we write to it.
TARGETS = (SECRETS_ENV, CREDENTIALS)


def _die(message: str) -> "NoReturn":  # noqa: F821 - typing only
    print(f"generate_nao_secrets: {message}", file=sys.stderr)
    raise SystemExit(1)


def _is_git_ignored(path: Path) -> bool:
    """True iff ``git check-ignore`` confirms the path is ignored in this repo."""
    try:
        result = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "check-ignore", "--quiet", str(path)],
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:  # git not installed
        return False
    return result.returncode == 0


def _assert_ignored() -> None:
    for path in TARGETS:
        # A file need not exist for check-ignore; a parent-dir rule still matches.
        if not _is_git_ignored(path):
            _die(f"refusing to write {path}: it is NOT git-ignored. Fix .gitignore first (wrote nothing).")


def _read_existing() -> Path | None:
    return SECRETS_ENV if SECRETS_ENV.exists() else None


def _write_env(path: Path, app_user_id: str) -> None:
    lines = [
        "# nao sidecar secrets (Task 3N) — git-ignored, generated by secrets/generate_nao_secrets.py.",
        "# Loaded by the nao service (env_file) and by the backend as the matching COPILOT_MCP_SECRET.",
        f"BETTER_AUTH_SECRET={secrets.token_urlsafe(48)}",
        f"COPILOT_MCP_SECRET={secrets.token_urlsafe(48)}",
        f"COPILOT_MCP_DISCOVERY_TOKEN={secrets.token_urlsafe(32)}",
        # Reserved .invalid TLD (RFC 2606): no mail can ever be delivered to it.
        f"NAO_SERVICE_EMAIL=svc+{uuid.uuid4().hex[:12]}@nao.invalid",
        f"NAO_SERVICE_PASSWORD={secrets.token_urlsafe(32)}",
        f"NAO_APP_USER_ID={app_user_id}",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    path.chmod(0o600)


def _ensure_credentials(path: Path) -> bool:
    """Create the credential store empty if missing (0600). Never overwrite existing data."""
    if path.exists():
        path.chmod(0o600)
        return False
    path.write_text("{}\n", encoding="utf-8")
    path.chmod(0o600)
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate git-ignored nao sidecar secrets.")
    parser.add_argument(
        "--app-user-id",
        default="",
        help="Copilot app user id to map onto the nao service account (recorded as NAO_APP_USER_ID).",
    )
    args = parser.parse_args()

    _assert_ignored()  # first, before any file operation

    DATA_DIR.mkdir(parents=True, exist_ok=True)

    existing = _read_existing()
    if existing is not None:
        print(f"generate_nao_secrets: {existing} already exists — leaving it unchanged (no rotation).")
    else:
        _write_env(SECRETS_ENV, args.app_user_id)
        print(f"generate_nao_secrets: wrote {SECRETS_ENV} (values not shown).")

    created = _ensure_credentials(CREDENTIALS)
    print(f"generate_nao_secrets: credential store {'created' if created else 'present'}: {CREDENTIALS}")
    print("generate_nao_secrets: 5 secrets ensured; none were printed.")


if __name__ == "__main__":
    main()
